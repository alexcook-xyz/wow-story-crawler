"""Race-starter summary for docs/race-gaps.md, generated from the crawl.

Counts come from the same find_gaps() the build uses (cli._gaps_for), so
the document cannot drift from `crawl_story.py build`.
"""
from __future__ import annotations

import collections

# Storyline chapters that are a race's starter. Labels come from each
# chapter's `race` field in seeds.json.
RACE_STARTERS = frozenset({
    "dwarf_coldrige", "dwarf_lodgings", "gnome_leper", "nightelf_shadowglen",
    "orc_valley_trials", "troll_valley_trials", "undead_deathknell",
    "tauren_red_cloud",
})


def race_report(shapes: list[dict], gaps: list, command: str) -> str:
    open_by: collections.Counter = collections.Counter()
    expl_by: collections.Counter = collections.Counter()
    for g in gaps:
        if g.chapter:
            (expl_by if g.explained else open_by)[g.chapter] += 1
    rows = [(s["id"], s.get("race") or "", len(s["quests"]), s["entry"],
             s["exit"], open_by[s["id"]], expl_by[s["id"]])
            for s in shapes if s["id"] in RACE_STARTERS]
    clean = [r[0] for r in rows if r[5] == 0]
    still = [f"{r[0]} {r[5]}" for r in rows if r[5]]
    table = [f"| {cid} | {race} | {n} | {entry} -> {exit_} | {op} | {ex} |"
             for cid, race, n, entry, exit_, op, ex in rows]
    lines = [
        "# Race gap summary (generated)",
        "",
        f"Generated by `{command}`. Do not edit by hand.",
        "",
        "| Chapter | Race | Quests | Entry -> exit | Open | Explained |",
        "|---|---|---|---|---|---|",
        *table,
        "",
        f"{len(clean)} of {len(rows)} race chapters have zero open gaps"
        + (f" ({', '.join(clean)})." if clean else "."),
    ]
    if still:
        lines.append(f"Still open: {', '.join(still)}.")
    return "\n".join(lines) + "\n"
